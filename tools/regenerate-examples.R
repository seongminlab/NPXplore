#!/usr/bin/env Rscript
# Run from any directory. Only the output path and grouping variable are supplied
# to npx_pipeline(); QC, statistics, plotting and functional stages keep defaults.
npx_example_specs <- function() {
  data.frame(Variable = c("Condition", "Group"),
             Directory = c("Paired_sample_test", "multiple_group_sample_test"),
             Metadata = c("example/metadata_HC_vs_Cancer.csv", "example/metadata_human_dilute.csv"))
}

npx_example_root <- function() {
  flag <- grep("^--file=", commandArgs(), value = TRUE)
  if (!length(flag)) stop("Run this tool with Rscript.")
  normalizePath(file.path(dirname(sub("^--file=", "", flag[1])), ".."), mustWork = TRUE)
}

npx_example_sha <- function(path) {
  if (!requireNamespace("digest", quietly = TRUE)) stop("The installed digest package is required for SHA256 checks.")
  vapply(path, function(value) digest::digest(file = value, algo = "sha256"), character(1), USE.NAMES = FALSE)
}

npx_example_manifest <- function(root) {
  paths <- c("DESCRIPTION", "NAMESPACE", unlist(lapply(c("R", "src", "inst", "tools"), function(directory) {
    file.path(directory, list.files(file.path(root, directory), recursive = TRUE,
                                    full.names = FALSE, all.files = FALSE))
  }), use.names = FALSE))
  paths <- paths[file.exists(file.path(root, paths)) & !dir.exists(file.path(root, paths))]
  inputs <- c("example/NPXfile.parquet", npx_example_specs()$Metadata)
  if (!all(file.exists(file.path(root, inputs)))) stop("Example inputs are missing from the source checkout.")
  paths <- sort(unique(c(paths, inputs)))
  data.frame(Kind = ifelse(paths %in% inputs, "Input", "Source"), Path = paths,
             SHA256 = npx_example_sha(file.path(root, paths)), stringsAsFactors = FALSE)
}

npx_example_manifest_hash <- function(manifest, kind = NULL) {
  if (!is.null(kind)) manifest <- manifest[manifest$Kind == kind, , drop = FALSE]
  digest::digest(paste(paste(manifest$Kind, manifest$Path, manifest$SHA256, sep = "\t"), collapse = "\n"),
                 algo = "sha256", serialize = FALSE)
}

npx_example_assert_manifest <- function(root, expected) {
  if (!identical(npx_example_manifest(root), expected)) stop("Source or inputs changed during generation; use a fresh output root after freezing the source.")
}

npx_example_git <- function(root, manifest) {
  repository <- Sys.getenv("NPXPLORE_SOURCE_REPOSITORY", root)
  git <- function(args) {
    out <- suppressWarnings(system2("git", c("-C", shQuote(repository), args), stdout = TRUE, stderr = FALSE))
    if (!is.null(attr(out, "status"))) stop("Cannot read source Git history. Set NPXPLORE_SOURCE_REPOSITORY to the original checkout.")
    out
  }
  head <- git(c("rev-parse", "HEAD"))
  status <- git(c("status", "--porcelain", "--untracked-files=normal"))
  source <- manifest[manifest$Kind == "Source", , drop = FALSE]
  matches <- vapply(seq_len(nrow(source)), function(i) {
    path <- tempfile(); on.exit(unlink(path))
    code <- suppressWarnings(system2("git", c("-C", shQuote(repository), "show", shQuote(paste0(head, ":", source$Path[i]))),
                                    stdout = path, stderr = FALSE))
    identical(code, 0L) && identical(npx_example_sha(path), source$SHA256[i])
  }, logical(1))
  list(SourceGitCommit = head[1], SourceGitRepository = normalizePath(repository),
       SourceGitDirty = length(status) > 0L, SourceSnapshotMatchesGitHead = all(matches),
       SourceDirty = length(status) > 0L || !all(matches), SourceGitStatus = paste(status, collapse = "\n"))
}

npx_example_defaults <- function() {
  values <- formals(NPXplore::npx_pipeline)
  values <- values[setdiff(names(values), c("data_file", "meta_file"))]
  vapply(values, function(value) paste(deparse(value), collapse = " "), character(1))
}

npx_example_membership <- function(meta, variable, result) {
  qc <- getFromNamespace("npx_qc_metadata", "NPXplore")(result$qc, meta)
  out <- meta
  out$SourceGroup <- as.character(meta[[variable]])
  out$QC <- qc$QC[match(meta$SampleID, qc$SampleID)]
  out$Included <- meta$SampleID %in% result$meta$SampleID
  out$ExportedGroup <- as.character(result$meta[[variable]][match(meta$SampleID, result$meta$SampleID)])
  out
}

npx_example_summary <- function(output_root) {
  specs <- npx_example_specs()
  paths <- file.path(output_root, specs$Directory, "log", "run_manifest.csv")
  rows <- lapply(paths[file.exists(paths)], function(path) read.csv(path, check.names = FALSE, stringsAsFactors = FALSE))
  if (!length(rows)) return(invisible(NULL))
  summary <- do.call(rbind, rows)
  utils::write.csv(summary, file.path(output_root, "REPRODUCIBILITY.csv"), row.names = FALSE)
  lines <- c("# Example reproducibility", "", "Generated by tools/regenerate-examples.R from the recorded source snapshot.",
             "The pipeline receives only data, metadata, output_dir and (for the multi-group run) variable = \"Group\".",
             "All other pipeline arguments use their recorded defaults. Functional stages may depend on external services; their actual statuses are recorded.",
             "", "A Git commit identifies the baseline. SourceDirty and SourceSnapshotMatchesGitHead disclose local changes; source_manifest.csv pins the exact source and inputs.",
             "Each log directory contains run_manifest.csv, source_manifest.csv, pipeline_defaults.csv, sample_membership.csv and sessionInfo.txt.",
             "", "| Example | Version | Git baseline | Dirty snapshot | Samples | Assays tested | DEPs | Run status |",
             "| --- | --- | --- | --- | ---: | ---: | ---: | --- |")
  lines <- c(lines, apply(summary, 1L, function(row) paste0("| ", paste(row[c("Example", "PackageVersion", "SourceGitCommit", "SourceDirty", "Samples", "StatisticalResults", "DEPs", "RunStatus")], collapse = " | "), " |")),
             "", "Verify QC membership and exported numerical tables offline with:", "", "```sh", "Rscript tools/check-examples.R /path/to/output-root", "```",
             "", "Source scope: DESCRIPTION, NAMESPACE, R/, src/, inst/ and tools/. All three example input files are pinned for both runs.")
  writeLines(lines, file.path(output_root, "REPRODUCIBILITY.md"))
}

npx_regenerate_examples <- function(args = commandArgs(trailingOnly = TRUE)) {
  if (!length(args) || args[1] %in% c("-h", "--help")) {
    cat("Usage: Rscript tools/regenerate-examples.R <new-output-root> [Condition|Group|all]\n",
        "Set NPXPLORE_SOURCE_REPOSITORY when the source snapshot is outside its Git checkout.\n", sep = "")
    return(invisible(NULL))
  }
  if (length(args) > 2L) stop("Too many arguments; use --help.")
  root <- npx_example_root()
  output_root <- normalizePath(args[1], mustWork = FALSE)
  if (!grepl("^/", output_root)) output_root <- file.path(getwd(), output_root)
  if (startsWith(paste0(output_root, "/"), paste0(root, "/"))) stop("Use an output root outside the source checkout.")
  selection <- if (length(args) == 2L) match.arg(args[2], c("Condition", "Group", "all")) else "all"
  specs <- npx_example_specs()
  selected <- specs[selection == "all" | specs$Variable == selection, , drop = FALSE]
  if (any(file.exists(file.path(output_root, selected$Directory)))) stop("Selected output directories already exist; choose a fresh output root.")
  pkgload::load_all(root, quiet = TRUE, export_all = FALSE)
  pinned <- npx_example_manifest(root)
  existing <- file.path(output_root, specs$Directory, "log", "source_manifest.csv")
  for (path in existing[file.exists(existing)]) {
    if (!identical(read.csv(path, stringsAsFactors = FALSE), pinned)) stop("Existing runs use different source or inputs; choose a fresh output root.")
  }
  git <- npx_example_git(root, pinned)
  defaults <- npx_example_defaults()
  seed_text <- Sys.getenv("NPXPLORE_SEED", "20261016")
  seed <- suppressWarnings(as.integer(seed_text))
  if (is.na(seed) || as.character(seed) != seed_text || seed < 0L) stop("NPXPLORE_SEED must be a non-negative integer.")
  data <- OlinkAnalyze::read_npx(file.path(root, "example/NPXfile.parquet"))
  for (i in seq_len(nrow(selected))) {
    spec <- selected[i, ]
    npx_example_assert_manifest(root, pinned)
    output <- file.path(output_root, spec$Directory)
    log_dir <- file.path(output, "log")
    dir.create(log_dir, recursive = TRUE, showWarnings = FALSE)
    utils::write.csv(pinned, file.path(log_dir, "source_manifest.csv"), row.names = FALSE)
    utils::write.csv(pinned[pinned$Kind == "Input", , drop = FALSE], file.path(log_dir, "input_manifest.csv"), row.names = FALSE)
    utils::write.csv(data.frame(Argument = names(defaults), Default = unname(defaults)), file.path(log_dir, "pipeline_defaults.csv"), row.names = FALSE)
    meta <- read.csv(file.path(root, spec$Metadata), check.names = FALSE, stringsAsFactors = FALSE)
    manifest <- c(list(Example = spec$Directory, Variable = spec$Variable, PackageVersion = as.character(utils::packageVersion("NPXplore"))), git,
                  list(SourceSHA256 = npx_example_manifest_hash(pinned, "Source"), InputSHA256 = npx_example_manifest_hash(pinned, "Input"),
                       Seed = seed, RNGKind = paste(RNGkind(), collapse = ";"), RVersion = R.version.string,
                       StartedUTC = format(Sys.time(), tz = "UTC", usetz = TRUE), CompletedUTC = "", RunStatus = "Running", Error = "",
                       MetadataSamples = nrow(meta), Samples = NA_integer_, PreparedAssays = NA_integer_, StatisticalResults = NA_integer_, DEPs = NA_integer_,
                       AssayBoxplotsStatus = "NotRun", ClusteringStatus = "NotRun", GOStatus = "NotRun", PPIStatus = "NotRun"),
                  setNames(as.list(defaults), paste0("Default_", names(defaults))))
    save_manifest <- function(value = manifest) utils::write.csv(as.data.frame(value, stringsAsFactors = FALSE), file.path(log_dir, "run_manifest.csv"), row.names = FALSE)
    save_manifest()
    set.seed(seed)
    tryCatch({
      call_args <- list(data_file = data, meta_file = meta, output_dir = output)
      if (spec$Variable != "Condition") call_args$variable <- spec$Variable
      result <- do.call(NPXplore::npx_pipeline, call_args)
      npx_example_assert_manifest(root, pinned)
      membership <- npx_example_membership(meta, spec$Variable, result)
      if (any(membership$Included & membership$QC == "FAIL")) stop("Default run included a FAIL sample.")
      utils::write.csv(membership, file.path(log_dir, "sample_membership.csv"), row.names = FALSE)
      manifest$Samples <- nrow(result$meta)
      manifest$PreparedAssays <- length(unique(result$data$Assay))
      manifest$StatisticalResults <- nrow(result$analysis$result)
      manifest$DEPs <- nrow(result$analysis$deps)
      for (stage in c("Clustering", "GO", "PPI")) manifest[[paste0(stage, "Status")]] <- result$diagnostics$Status[match(stage, result$diagnostics$Stage)]
      run_log <- readLines(result$output_files$run_log, warn = FALSE)
      status <- grep("Stage status: Assay boxplots=", run_log, value = TRUE)
      manifest$AssayBoxplotsStatus <- if (length(status)) sub(".*Assay boxplots=([^;]+);.*", "\\1", tail(status, 1L)) else "Unknown"
      manifest$RunStatus <- "Complete"
      manifest$CompletedUTC <- format(Sys.time(), tz = "UTC", usetz = TRUE)
      save_manifest(manifest)
      writeLines(capture.output(utils::sessionInfo()), file.path(log_dir, "sessionInfo.txt"))
      npx_example_summary(output_root)
    }, error = function(e) {
      manifest$RunStatus <- "Failed"
      manifest$Error <- conditionMessage(e)
      manifest$CompletedUTC <- format(Sys.time(), tz = "UTC", usetz = TRUE)
      save_manifest(manifest)
      writeLines(capture.output(utils::sessionInfo()), file.path(log_dir, "sessionInfo.txt"))
      npx_example_summary(output_root)
      stop(e)
    })
  }
  invisible(output_root)
}

if (sys.nframe() == 0L) npx_regenerate_examples()
